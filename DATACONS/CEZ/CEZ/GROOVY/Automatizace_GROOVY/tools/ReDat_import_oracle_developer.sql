-- ReDat import (Oracle SQL Developer)
-- UTF-8 import + pevny format CREATED_DATE: DD.MM.RRRR HH24:MI:SS
--
-- POZOR:
-- 1) DIRECTORY cesta musi byt viditelna z Oracle DB serveru (ne z lokalniho PC SQL Developeru).
-- 2) Pokud DB server nevidi O:, namapuj UNC cestu (napr. \\server\share\EXPORTY_pravidelny_prenos\ReDat\Script).

-- ===== 1) Nastav cestu (uprav podle prostredi) =====
CREATE OR REPLACE DIRECTORY REDAT_IMPORT_DIR AS 'O:\EXPORTY_pravidelny_prenos\ReDat\Script';
GRANT READ, WRITE ON DIRECTORY REDAT_IMPORT_DIR TO MRENCAKAR;

-- ===== 2) EXTERNAL TABLE pro CSV =====
-- Delimiter je carka, text je v uvozovkach, encoding UTF-8 (AL32UTF8).
CREATE TABLE MRENCAKAR.RDTT_TOPS_IMPORT_EXT
(
  XTTOPS_EFFECTIVE_DATE  VARCHAR2(20),
  XTTOPS_R_ID_ZDR        VARCHAR2(50),
  XTTOPS_TOPK_SK         VARCHAR2(100),
  XTTOPS_TOPK            VARCHAR2(4000),
  XTTOPS_TOPK_FLG        VARCHAR2(20),
  XTTOPS_RELEVANCE       VARCHAR2(20),
  XTTOPS_DAT_EXPORTU     VARCHAR2(30),
  XTTOPS_GRPS_FILENAME   VARCHAR2(400),
  XTTOPS_GRPS_FILEPATH   VARCHAR2(1000),
  XTTOPS_GRPS_LOADDATE   VARCHAR2(30),
  XTTOPS_CREATED_DATE    VARCHAR2(30),
  XTTOPS_CREATED_PROCESS VARCHAR2(400)
)
ORGANIZATION EXTERNAL
(
  TYPE ORACLE_LOADER
  DEFAULT DIRECTORY REDAT_IMPORT_DIR
  ACCESS PARAMETERS
  (
    RECORDS DELIMITED BY NEWLINE
    CHARACTERSET AL32UTF8
    BADFILE  REDAT_IMPORT_DIR:'redat_import.bad'
    LOGFILE  REDAT_IMPORT_DIR:'redat_import.log'
    SKIP 1
    FIELDS TERMINATED BY ',' OPTIONALLY ENCLOSED BY '"'
    LRTRIM
    MISSING FIELD VALUES ARE NULL
  )
  LOCATION ('Redat_soubory.csv')
)
REJECT LIMIT UNLIMITED;

-- ===== 3) Nahrani do cilove tabulky =====
-- Pokud nechces mazat historicka data, smaz TRUNCATE.
TRUNCATE TABLE MRENCAKAR.RDTT_TOPS_IMPORT_CSV;

INSERT INTO MRENCAKAR.RDTT_TOPS_IMPORT_CSV
(
  XTTOPS_EFFECTIVE_DATE,
  XTTOPS_R_ID_ZDR,
  XTTOPS_TOPK_SK,
  XTTOPS_TOPK,
  XTTOPS_TOPK_FLG,
  XTTOPS_RELEVANCE,
  XTTOPS_DAT_EXPORTU,
  XTTOPS_GRPS_FILENAME,
  XTTOPS_GRPS_FILEPATH,
  XTTOPS_GRPS_LOADDATE,
  XTTOPS_CREATED_DATE,
  XTTOPS_CREATED_PROCESS
)
SELECT
  TO_NUMBER(XTTOPS_EFFECTIVE_DATE),
  TO_NUMBER(XTTOPS_R_ID_ZDR),
  XTTOPS_TOPK_SK,
  XTTOPS_TOPK,
  XTTOPS_TOPK_FLG,
  TO_NUMBER(XTTOPS_RELEVANCE),
  TO_DATE(XTTOPS_DAT_EXPORTU,   'DD.MM.RRRR HH24:MI:SS'),
  XTTOPS_GRPS_FILENAME,
  XTTOPS_GRPS_FILEPATH,
  TO_DATE(XTTOPS_GRPS_LOADDATE, 'DD.MM.RRRR HH24:MI:SS'),
  TO_DATE(XTTOPS_CREATED_DATE,  'DD.MM.RRRR HH24:MI:SS'),
  XTTOPS_CREATED_PROCESS
FROM MRENCAKAR.RDTT_TOPS_IMPORT_EXT;

COMMIT;

-- ===== 4) Kontrola =====
SELECT COUNT(*) AS POCET_RADKU FROM MRENCAKAR.RDTT_TOPS_IMPORT_CSV;

